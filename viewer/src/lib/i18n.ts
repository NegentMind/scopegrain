export function t(locale: Locale, key: string): string {
  return DICT[locale][key] ?? DICT.en[key] ?? key;
}

export function dictKeys(locale: Locale): string[] {
  return Object.keys(DICT[locale]);
}

export function useT() {
  const locale = useLocale();
  return (key: string) => t(locale, key);
}

// Enum/code values from records: localized when a `<prefix>.<value>` key
// exists, raw otherwise (project-defined values stay verbatim).
export function useTEnum() {
  const locale = useLocale();
  return (prefix: string, value: string | null | undefined) => {
    if (!value) return value;
    const key = `${prefix}.${value}`;
    const tr = t(locale, key);
    return tr === key ? value : tr;
  };
}

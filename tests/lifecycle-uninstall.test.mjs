// Lifecycle: uninstall preview/apply -- deletes only provably harness files.
import test, { after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {
  applyUninstall, prepareUninstall,
} from '../src/core/lifecycle.mjs';
import {
  cleanup, exists, readJson, writeFile, writeJson,
} from './helpers.mjs';
import {
  bootstrappedMiniCtx, configuredCtx, destroyLifecycleInstall, enroll,
  snapshot,
} from './helpers/lifecycle-fixture.mjs';

after(() => destroyLifecycleInstall());

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

test('uninstall preview: candidates are only provably harness-created files', () => {
  const { dir, ctx, installRoot } = bootstrappedMiniCtx();
  try {
    enroll(ctx);
    writeFile(dir, '.tasksystem/plans/user.json', '{}');
    const before = snapshot(dir);
    const preview = prepareUninstall(ctx, { installRoot });
    assert.deepEqual(snapshot(dir), before); // read-only
    assert.equal(preview.mode, 'dry-run');
    const rels = preview.candidates.map((c) => c.rel);
    assert.ok(rels.includes('.tasksystem/config.json'));
    assert.ok(rels.includes('.tasksystem/task-contract.md'));
    assert.ok(rels.includes('.tasksystem/instructions.md'));
    assert.ok(rels.includes('.tasksystem/state/workspace.json'));
    assert.ok(rels.includes('.tasksystem/catalog.json'));
    assert.ok(rels.includes('CLAUDE.md')); // generated entrypoint at root
    // user artifact under a declared path is NEVER a candidate
    assert.ok(!rels.includes('.tasksystem/plans/user.json'));
    for (const c of preview.candidates) {
      assert.match(c.sha256, /^[0-9a-f]{64}$/);
      assert.ok(['config', 'generated', 'snapshot-pinned', 'state']
        .includes(c.reason));
    }
  } finally { cleanup(dir); }
});

test('uninstall preview: diverged generated file is leftBehind not candidate', () => {
  const { dir, ctx, installRoot } = bootstrappedMiniCtx();
  try {
    writeFile(dir, '.tasksystem/task-contract.md', 'user edited');
    const preview = prepareUninstall(ctx, { installRoot });
    assert.ok(!preview.candidates.some(
      (c) => c.rel === '.tasksystem/task-contract.md'));
    assert.ok(preview.leftBehind.some(
      (l) => l.rel === '.tasksystem/task-contract.md'));
  } finally { cleanup(dir); }
});

test('uninstall preview: unmodified file pinned by snapshot hash is a candidate', () => {
  const { dir, ctx, installRoot } = bootstrappedMiniCtx();
  try {
    // Simulate an older-install resource: on-disk bytes differ from what the
    // current install regenerates but match the project snapshot pin.
    const rel = '.tasksystem/commands/plan-work.md';
    const abs = path.join(dir, rel);
    const mutated = Buffer.concat([fs.readFileSync(abs), Buffer.from('x')]);
    fs.writeFileSync(abs, mutated);
    const catalog = readJson(dir, '.tasksystem/catalog.json');
    const entry = catalog.entries.find((e) => e.path === 'commands/plan-work.md');
    assert.ok(entry, 'fixture must contain the catalog entry');
    entry.sha256 = sha(mutated);
    writeJson(dir, '.tasksystem/catalog.json', catalog);
    // catalog.json itself diverged from generated bytes -- leftBehind
    const preview = prepareUninstall(ctx, { installRoot });
    const cand = preview.candidates.find((c) => c.rel === rel);
    assert.ok(cand, 'snapshot-pinned file should be a candidate');
    assert.equal(cand.reason, 'snapshot-pinned');
    assert.ok(preview.leftBehind.some(
      (l) => l.rel === '.tasksystem/catalog.json'));
  } finally { cleanup(dir); }
});

test('applyUninstall deletes matching files, leaves user and diverged files', () => {
  const { dir, ctx, installRoot } = bootstrappedMiniCtx();
  try {
    enroll(ctx);
    writeFile(dir, '.tasksystem/plans/user.json', '{}');
    writeFile(dir, '.tasksystem/task-contract.md', 'user edited');
    const res = applyUninstall(ctx, { installRoot });
    assert.equal(res.mode, 'applied');
    assert.ok(res.deleted.includes('.tasksystem/config.json'));
    assert.ok(res.deleted.includes('.tasksystem/state/workspace.json'));
    assert.ok(res.deleted.includes('CLAUDE.md'));
    // diverged and user files survive
    assert.ok(res.leftBehind.some(
      (l) => l.rel === '.tasksystem/task-contract.md'));
    assert.ok(exists(dir, '.tasksystem/task-contract.md'));
    assert.equal(fs.readFileSync(
      path.join(dir, '.tasksystem/task-contract.md'), 'utf8'), 'user edited');
    assert.ok(exists(dir, '.tasksystem/plans/user.json'));
    // emptied harness dirs removed bottom-up; non-empty dirs stay
    assert.ok(!exists(dir, '.tasksystem/state'));
    assert.ok(!exists(dir, '.tasksystem/commands'));
    assert.ok(exists(dir, '.tasksystem')); // still holds leftBehind + user file
    assert.ok(fs.statSync(dir).isDirectory()); // project root untouched
    // catalog-projection dirs emptied -> removed
    assert.ok(!exists(dir, '.tasksystem/skills'));
  } finally { cleanup(dir); }
});

test('applyUninstall on minimal config removes config-dir subtree only', () => {
  const { dir, ctx, installRoot } = bootstrappedMiniCtx();
  try {
    const res = applyUninstall(ctx, { installRoot });
    assert.equal(res.mode, 'applied');
    assert.ok(res.deleted.length > 0);
    assert.ok(!exists(dir, '.tasksystem'));
    assert.ok(!exists(dir, 'CLAUDE.md'));
    assert.ok(fs.statSync(dir).isDirectory());
    assert.ok(Array.isArray(res.removedDirs));
  } finally { cleanup(dir); }
});

test('uninstall rejects unknown options', () => {
  const { dir, ctx } = configuredCtx();
  try {
    assert.throws(() => prepareUninstall(ctx, { nope: 1 }),
      (e) => e.code === 'LIFECYCLE_INVALID_INPUT');
  } finally { cleanup(dir); }
});
